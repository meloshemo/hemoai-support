  // Health Status Colors
  static Color getHealthStatusColor(String status) {
    switch (status.toLowerCase()) {
      case 'normal':
      case 'good':
        return healthGood;
      case 'warning':
      case 'moderate':
        return healthWarning;
      case 'critical':
      case 'high':
        return healthCritical;
      case 'info':
      case 'low':
        return healthInfo;
      default:
        return Colors.grey;
    }
  }
  
  // Health Status Text Style
  static TextStyle getHealthStatusTextStyle(String status) {
    return TextStyle(
      color: getHealthStatusColor(status),
      fontWeight: FontWeight.w600,
    );
  }
  
  // Gradient Colors for Health Cards
  static LinearGradient getHealthCardGradient(String status) {
    final color = getHealthStatusColor(status);
    return LinearGradient(
      colors: [
        color.withOpacity(0.1),
        color.withOpacity(0.05),
      ],
      begin: Alignment.topLeft,
      end: Alignment.bottomRight,
    );
  }
  
